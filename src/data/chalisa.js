/* plain-text version for download */
export function chalisaAsText(lang = "hi") {
  const lines = [
    "॥ श्री हनुमान चालीसा ॥",
    "— गोस्वामी तुलसीदास कृत —",
    "",
  ];
  for (const v of chalisa.verses) {
    lines.push(`[${v.kind}]`);
    lines.push(...v.dev);
    lines.push(lang === "en" ? `Meaning: ${v.en}` : `अर्थ: ${v.hi}`);
    lines.push("");
  }
  lines.push("॥ जय श्री राम ॥", "", "— pujapath se download kiya gaya —");
  return lines.join("\r\n");
}
